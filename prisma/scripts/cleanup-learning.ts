async function main() {
  console.log("=== Learning Cleanup Start ===\n");

  // 1. 重複コース削除
  console.log("1. 重複コース削除...");
  for (const title of DUPLICATE_TITLES) {
    const course = await db.learningCourse.findFirst({ where: { title } });
    if (course) {
      await db.learningCourse.delete({ where: { id: course.id } });
      console.log(`   DELETE: ${title}`);
    } else {
      console.log(`   SKIP: ${title} (not found)`);
    }
  }

  // 2. mediaType 設定
  console.log("\n2. mediaType設定...");
  for (const [title, mediaType] of Object.entries(MEDIA_TYPE_MAP)) {
    const course = await db.learningCourse.findFirst({ where: { title } });
    if (course) {
      await db.learningCourse.update({
        where: { id: course.id },
        data: { mediaType: mediaType as any },
      });
      console.log(`   SET: ${title} → ${mediaType}`);
    }
  }

  // 3. テキストレッスン本文追加
  console.log("\n3. テキストレッスン本文追加...");
  for (const [courseTitle, lessons] of Object.entries(LESSON_BODIES)) {
    const course = await db.learningCourse.findFirst({
      where: { title: courseTitle },
      include: { lessons: true },
    });
    if (!course) {
      console.log(`   SKIP: ${courseTitle} (course not found)`);
      continue;
    }

    for (const [lessonTitle, body] of Object.entries(lessons)) {
      const lesson = course.lessons.find((l) => l.title === lessonTitle);
      if (lesson) {
        await db.learningLesson.update({
          where: { id: lesson.id },
          data: { body, type: "text" },
        });
        console.log(`   UPDATE: ${courseTitle} > ${lessonTitle}`);
      } else {
        console.log(`   SKIP: ${courseTitle} > ${lessonTitle} (lesson not found)`);
      }
    }
  }

  // 4. 動画レッスンをテキスト+外部リンクに変更
  console.log("\n4. 動画レッスンを外部リンク化...");
  const videoLessons = await db.learningLesson.findMany({
    where: { type: "video" },
  });
  for (const lesson of videoLessons) {
    // contentUrlがpreview形式の場合、view形式に変換
    let url = lesson.contentUrl;
    if (url?.includes("/preview")) {
      url = url.replace("/preview", "/view");
    }
    await db.learningLesson.update({
      where: { id: lesson.id },
      data: { contentUrl: url },
    });
    console.log(`   FIX: ${lesson.title} → external link`);
  }

  // 5. 結果確認
  console.log("\n=== 結果確認 ===");
  const remaining = await db.learningCourse.findMany({
    where: { published: true },
    include: {
      lessons: { select: { id: true, title: true, type: true, body: true } },
      tests: { select: { id: true, title: true } },
    },
    orderBy: { sortOrder: "asc" },
  });

  for (const c of remaining) {
    const hasBody = c.lessons.filter((l) => l.body).length;
    console.log(`  [${c.sortOrder}] ${c.title} — ${c.lessons.length}教材(本文${hasBody}件), ${c.tests.length}テスト, mediaType=${c.mediaType ?? "null"}`);
  }

  console.log(`\n合計: ${remaining.length}コース`);
  console.log("\n=== Done! ===");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
