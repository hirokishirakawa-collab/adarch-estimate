async function main() {
  console.log("Wiki seed start...");

  // 投稿者の Branch を取得
  const hq = await db.branch.findFirst({ where: { id: "branch_hq" } });
  if (!hq) {
    throw new Error("Branch branch_hq が見つかりません");
  }

  for (const a of ARTICLES) {
    const existing = await db.wikiArticle.findFirst({ where: { title: a.title } });
    if (existing) {
      console.log(`  SKIP: ${a.title}`);
      continue;
    }
    await db.wikiArticle.create({
      data: {
        title: a.title,
        body: a.body,
        authorName: "白川 裕喜",
        branchId: hq.id,
      },
    });
    console.log(`  OK: ${a.title}`);
  }

  console.log("Done!");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
