import { config } from "dotenv";
config({ path: ".env.local" });
import { PrismaClient } from "../../src/generated/prisma/client";
import { PrismaPg } from "@prisma/adapter-pg";
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL as string }) });

const OLD_TITLE = "広告賞ファインダーの使い方 — 制作物に「受賞」の箔を付けて提案する";
const NEW_TITLE = "広告賞ファインダーの使い方 — 「この賞に出しませんか」をクライアントとの会話のきっかけに";
const PREV_TITLE = "広告賞ファインダーの使い方 — 納品した作品を「この賞に出しませんか」と追加提案する";
const BODY = `# 広告賞ファインダーの使い方

## この機能でできること
- 全国・地方・国際の広告賞（174件）の応募時期・応募料・対象・狙いやすさを一覧できる
- あなたの県の **地元の賞**（広告協会賞・地方紙の広告賞・ラジオ局のCMコンテスト等）が最初に出る
- 「受付中・締切まで◯日」「次回◯月〜」の順に並ぶので、いまの作品に合う賞をすぐ選べる
- 「案内文をコピー」で、賞の名前・応募時期・応募料を1行にして、クライアントへの連絡にそのまま貼れる

## 使いどころ＝クライアントとのコミュニケーションのきっかけの一つ
- 制作前・制作中・完了後のどの段階でも使える。「せっかくなので◯◯賞に出しませんか」のひと言が、次の会話の入口になる
- 地元の賞は「県内で掲出・放送された広告」なら応募でき、応募料は無料〜数千円が大半。先方の負担が小さいので切り出しやすい
- 受賞後の使い道まで添えると話が広がる：地元紙への掲載・表彰式に先方も登壇・受賞マークを先方のサイトや名刺に

## 基本的な使い方
1. サイドバー「営業」から **広告賞ファインダー** を開く（都道府県は自分の拠点県が初期値。本部は全国）
2. 「制作物の種類」で、いま話している作品の種類（TVCM／WEB動画／新聞／OOH交通 など）を選ぶ
3. **◎（地元・応募すれば入賞圏）** から見る
4. 「案内文をコピー」を押して、クライアントへの連絡や打ち合わせのメモに貼る
5. 受付中でなければ「次回◯月〜」を控えておき、その時期に改めて声をかける

## 読み方の注意
- 広告賞は毎年ほぼ同じ内容で **日程だけが変わる**。画面の日程は確認した年の実績で、翌年分は「次回◯月頃（前年実績）」と出る
- **「日程は要確認」** と付いている賞は、先方に伝える前に主催の公式ページか事務局へ確認する（地方の広告協会賞は応募期間を公開していないところが多い）
- 「存在未確認」と付いている賞は、存在自体を確認できていないもの。必ず主催へ確認してから伝える
- 会員社限定・協会内コンテストの賞もある（対象欄に書いてある）。非会員が出せない賞は先方に案内しない
- ◎○△の狙いやすさは本部の見立て。実際の競争率は年によって変わる

## 困ったとき
- 該当が0件のときは、都道府県を「指定しない」にするか、範囲を「地元＋全国」「国際も含む」に広げる
- 賞の追加・日程の修正は本部（白川）まで。年1回、日程だけ更新する
`;

async function main() {
  const a = await db.wikiArticle.findFirst({ where: { title: { in: [OLD_TITLE, PREV_TITLE, NEW_TITLE] } } });
  if (!a) throw new Error("記事が見つかりません");
  await db.wikiArticle.update({ where: { id: a.id }, data: { title: NEW_TITLE, body: BODY } });
  console.log("updated:", a.id);
}
main().catch((e) => { console.error(e); process.exit(1); }).finally(() => db.$disconnect());
