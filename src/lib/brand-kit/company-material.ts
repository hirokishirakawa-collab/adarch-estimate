// ブランドキット — 会社紹介・実績の事実（AI用材料）
//   公開情報（コーポレートサイト会社概要）と、OSの拠点データから組む。
//   取引先の社名は載せない（営業文に書かない決まり）。会社概要ページへの案内だけ。
// ==============================================================

import { commonGuidelines, senderBlock, todayLabel } from "./common";
import type { MaterialSender } from "./material";

export const CORPORATE_SITE = "https://adarch.co.jp/";

export interface CompanyFactsInput {
  sender: MaterialSender | null;
  activeCompanies: number; // OSの稼働中の加盟会社数
  prefectures: string[]; // OSに登録された拠点の都道府県
}

export function buildCompanyMaterial(input: CompanyFactsInput): string {
  const asOf = todayLabel();
  const prefs = input.prefectures.filter(Boolean);
  return `# アドアーチグループ 会社紹介・実績の事実｜AI用の材料　${asOf}版（Ad Arch OS から自動生成）

> 提案メール・資料の「私たちは誰か」の部分に使う材料です。お使いのAIに貼っておくと、会社の説明が毎回同じ事実で出ます。
> 差出人はあくまで「1. あなたの会社」。本部の名義では書きません。

---

## 1. あなたの会社（差出人）　※空欄だけ自分で埋める

${senderBlock(input.sender)}

---

## 2. グループの事実（公開情報・コーポレートサイト会社概要より）

**グループ名**: Ad Arch（アドアーチ）グループ
**本部**: Ad Arch株式会社（読み: アドアーチ）／東京都港区南青山2-15-5 FARO 1階／代表取締役 白川 裕喜／設立 2016年1月
**事業内容**: 広告事業（広告企画・媒体プランニング・映像等クリエイティブ制作）
**実績（公開数字）**: 累計制作本数 2,000本以上／取引企業 500社以上（2016年創業〜グループ累計）／全国24拠点
**拠点のある都道府県（OSの登録・${asOf}時点）**: ${prefs.length ? prefs.join("・") : "（登録なし）"}（稼働中の加盟会社 ${input.activeCompanies}社）
**連絡先（本部）**: Tel 050-1793-9063（代表窓口・AI自動受付）／info@adarch.co.jp／${CORPORATE_SITE}

**考え方（サイトの言葉そのまま）**
何を、誰に、どの媒体で。広告の全体を設計するグループです。Ad Archは、広告企画・媒体プランニング・クリエイティブ制作を一気通貫で担う広告エージェンシーグループです。土台にあるのは、映像制作の現場で培ったクリエイティブ力。伝えるべきことの設計から配信まで、途中で分断させません。地域に根ざした全国の拠点網と、どの地域でも変わらないクリエイティブの品質。地域の一案件から全国キャンペーンまで、その両立でお応えします。

**事業・サービス（4つ）**
1. 広告企画・戦略設計 ― 事業課題の整理から、ターゲット設計・キャンペーン企画まで。「何を、誰に、どの媒体で」を最初に描く
2. 媒体プランニング ― コネクテッドTV・シネマ広告・OOH・デジタルサイネージなど、多彩な広告媒体から最適な組み合わせを設計する
3. クリエイティブ制作 ― CM・企業VPなどの映像から、LP・SNS・グラフィックまで。媒体に合わせた表現を企画から納品まで一貫制作
4. 全国対応体制 ― 全国の拠点が連携し、ローカル撮影・地方キャンペーン・多拠点プロジェクトに対応

**体制（お客様に言ってよいこと）**
- TVer正規代理店。媒体の契約当事者はお客様と当社で、間に何社も挟まない
- 全国に拠点を持つグループ。お客様の近隣エリアの担当が直接訪問できる（オンラインでも対面でも）
- 制作から運用まで一社で。CM制作・配信設計・レポートまで一貫
- 数字で報告する。リーチ人数・フリークエンシー・完全視聴率・県別実績を毎月報告
- 本部の立ち位置: 「地方の事業を全国的にPR」

**主要取引先**: コーポレートサイトの会社概要ページに掲載（${CORPORATE_SITE}company.html）。**営業文には社名を書かない**。「ナショナルブランドから自治体・地域企業まで、幅広い実績があります」と言い、詳しくは会社概要ページを案内する

---

## 3. 言い方の例

- 「私たちは、全国に拠点を持つ広告グループ Ad Arch の〇〇（県名）の拠点です。テレビCMの配信から映像制作まで、地元で一貫してお引き受けしています」
- 「大手の広告と同じ制作・運用のノウハウを、地域の企業の規模でお使いいただけます」
- 「お近くの拠点から直接お伺いします。配信の設定や毎月のレポートは本部が行い、窓口は私たちが務めます」

---

## 4. 言ってよいこと・言ってはいけないこと

${commonGuidelines()}

**この材料の注意**
- 数字は上の公開数字だけ。自社の拠点の実績数は、自社で把握しているものを別途書く
- 「本社品質」という言い方はしない（本社が偉い・地方が下請けという序列を匂わせる）。「どの地域でも変わらないクリエイティブの品質」と言う
- 取引先の社名を営業文に書かない

---

## 5. この材料について
- 出どころ: コーポレートサイト（会社概要・事業）、Ad Arch OS の拠点登録。${asOf}時点
- 更新: OSの「ブランドキット」を開くたびに最新`;
}
